#!/usr/bin/env node
/**
 * Generate the data tables of this plugin from AgentCompass's public reference data at the pinned commit
 * (`scripts/agentcompass-pin.mjs`; the checkout is `MAGPIE_AGENTCOMPASS_REPO` or `--agentcompass-repo <path>`):
 *
 *   src/catalog.js         the GENERATED block: `references/accounts.json` (model rows, aliases, families, launch efforts,
 *                          route scopes, scoring policy) and `plan-templates.json` (plan windows)
 *   src/reference-data.js  the whole file: `five-axis-scores.json` (panel targets with ceilings, per-model category scores,
 *                          durations, usd per hour, fast mode, plan capacities) and `user-scores.json` (maintainer scores)
 *
 *   node scripts/sync-catalog.mjs          rewrite both
 *   node scripts/sync-catalog.mjs --check  exit 1 if either differs from what the pinned commit generates
 *
 * Provenance prose (statements, urls, board sources) is dropped: nothing routes on it. Nothing is added or overridden here:
 * a model the pinned data does not list has no row.
 */
import fs from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { AGENTCOMPASS_COMMIT, agentCompassJson } from "./agentcompass-pin.mjs";

const REFERENCES = "skills/agent-compass/references";
export const ACCOUNTS_PATH = `${REFERENCES}/accounts.json`;
export const FIVE_AXIS_PATH = `${REFERENCES}/five-axis-scores.json`;
export const USER_SCORES_PATH = `${REFERENCES}/user-scores.json`;
export const PLAN_TEMPLATES_PATH = `${REFERENCES}/plan-templates.json`;
const CATALOG_PATH = fileURLToPath(new URL("../src/catalog.js", import.meta.url));
const REFERENCE_DATA_PATH = fileURLToPath(new URL("../src/reference-data.js", import.meta.url));
const BEGIN = "// BEGIN GENERATED by scripts/sync-catalog.mjs";
const END = "// END GENERATED by scripts/sync-catalog.mjs";

const PROSE_KEYS = new Set([
  "basis",
  "statement",
  "url",
  "pricing_url",
  "as_of",
  "listed_as",
  "list_price_source",
  "image_input_source",
  "calibration_source",
  "label",
]);

/** Provenance prose: long, and nothing routes on it. */
function dropProse(value) {
  if (Array.isArray(value)) return value.map(dropProse);
  if (!value || typeof value !== "object") return value;
  const out = {};
  for (const [key, val] of Object.entries(value)) {
    if (PROSE_KEYS.has(key) || key.endsWith("_basis")) continue;
    out[key] = dropProse(val);
  }
  return out;
}

const isRow = (row) => row && typeof row === "object" && !Array.isArray(row);
const rowsOf = (table) => Object.entries(table || {}).filter(([, row]) => isRow(row));
const sortedKeys = (obj) => Object.fromEntries(Object.keys(obj).sort().map((k) => [k, obj[k]]));

export function buildCatalogTables(accounts, planTemplates) {
  const models = {};
  for (const [name, row] of rowsOf(accounts.models)) models[name] = dropProse(row);

  const routes = {};
  for (const [kind, route] of Object.entries(accounts.capability_policy.routes)) {
    const { effort: _prose, role: _role, ...rest } = route;
    routes[kind] = rest;
  }

  const sameModel = {};
  for (const [name, row] of rowsOf(accounts.same_model)) {
    if (row.capacity_rule) {
      const { statement: _s, as_of: _a, kind: _k, ...rule } = row.capacity_rule;
      sameModel[name] = { model: row.model, capacity_rule: rule };
    }
  }

  const plans = {};
  for (const [family, table] of Object.entries(planTemplates)) {
    if (!isRow(table)) continue;
    plans[family] = {};
    for (const [plan, entry] of rowsOf(table)) {
      const { basis: _b, provenance: _p, price_source: source, ...rest } = entry;
      plans[family][plan] = {
        ...dropProse(rest),
        ...(source && source.kind === "vendor" && source.url ? { price_source: { kind: source.kind, url: source.url } } : {}),
      };
    }
  }

  return {
    MODELS: models,
    MODEL_ALIASES: accounts.aliases,
    FAMILIES: accounts.families.rows.map((row) => ({ pattern: row.pattern, models: row.models })),
    SUPERSEDED_MODELS: Object.fromEntries(rowsOf(accounts.superseded).map(([name, row]) => [name, row.by])),
    SAME_MODEL_CAPACITY_RULES: sameModel,
    DISPATCH_EFFORTS: accounts.dispatch_efforts,
    ROUTES: routes,
    QUOTA_SOURCES: accounts.quota_sources || {},
    SCORING_POLICY: dropProse(accounts.scoring),
    PLAN_TEMPLATES: plans,
  };
}

/** The axis cell the runtime reads: values, per-effort values and status, never the board sources behind them. */
function axisCell(cell) {
  if (!isRow(cell)) return cell;
  const out = {};
  for (const key of ["value", "by_effort", "status", "flag", "missing_facets", "measured_efforts"]) {
    if (cell[key] !== undefined) out[key] = cell[key];
  }
  if (isRow(cell.facets)) {
    out.facets = Object.fromEntries(Object.entries(cell.facets).map(([name, facet]) => [name, axisCell(facet)]));
  }
  if (isRow(cell.by_level)) out.by_level = cell.by_level;
  return out;
}

function modelRow(row) {
  const estimates = {};
  for (const [axis, cell] of Object.entries(row.axes || {})) {
    for (const [facet, comp] of Object.entries((cell && cell.facets) || {})) {
      if (comp && comp.status === "estimated") estimates[`${axis}.${facet}`] = { method: (comp.estimate || {}).method || null };
    }
  }
  const duration = row.duration_multiplier || {};
  const fast = row.fast_mode || { status: "not_offered" };
  return {
    categories: Object.fromEntries(Object.entries(row.axes || {}).map(([axis, cell]) => [axis, axisCell(cell)])),
    missing: row.missing_axes || [],
    estimates,
    tier: row.tier ? { value: row.tier.value, method: row.tier.method } : { value: null, method: "none" },
    usd_per_hour: row.usd_per_hour && row.usd_per_hour.value !== undefined ? row.usd_per_hour.value : null,
    image_input: { status: (row.image_input || { status: "missing" }).status, source: (row.image_input || {}).source || null },
    fast_mode: Object.fromEntries(
      ["status", "price_multiplier", "speed_multiplier", "reason"].filter((k) => fast[k] !== undefined).map((k) => [k, fast[k]]),
    ),
    duration: {
      ...(duration.status !== undefined ? { status: duration.status } : {}),
      by_effort: duration.by_effort || {},
      basis_by_effort: Object.fromEntries(
        Object.entries(duration.basis_by_effort || {}).map(([effort, basis]) => [effort, { method: basis.method, source: basis.source || null }]),
      ),
    },
  };
}

export function buildReferenceTables(fiveAxis, userScores) {
  const capacity = {};
  for (const [family, plans] of Object.entries(fiveAxis.capacity || {})) {
    capacity[family] = {};
    for (const [plan, windows] of Object.entries(plans)) {
      capacity[family][plan] = {};
      for (const [wid, row] of Object.entries(windows)) {
        capacity[family][plan][wid] = { capacity_usd: row.capacity_usd ?? null, status: row.status || "missing" };
      }
    }
  }
  const anchor = fiveAxis.anchor;
  return {
    FIVE_AXIS_SCHEMA: fiveAxis.schema,
    FIVE_AXIS_ANCHOR: { model: anchor.model, panel_n: anchor.panel_n, targets: anchor.targets },
    FIVE_AXIS_MODELS: Object.fromEntries(rowsOf(fiveAxis.models).map(([name, row]) => [name, modelRow(row)])),
    PLAN_CAPACITY: capacity,
    MAINTAINER_SCORES: sortedKeys(userScores.scores || {}),
  };
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const keyOf = (key) => (IDENTIFIER.test(key) ? key : JSON.stringify(key));

function literal(value, indent = "") {
  if (Array.isArray(value)) {
    if (value.every((v) => v === null || typeof v !== "object")) {
      const flat = `[${value.map((v) => JSON.stringify(v)).join(", ")}]`;
      if (flat.length + indent.length <= 110) return flat;
    }
    const inner = `${indent}  `;
    return `[\n${value.map((v) => `${inner}${literal(v, inner)},`).join("\n")}\n${indent}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    if (entries.every(([, v]) => v === null || typeof v !== "object")) {
      const flat = `{ ${entries.map(([k, v]) => `${keyOf(k)}: ${JSON.stringify(v)}`).join(", ")} }`;
      if (flat.length + indent.length <= 110) return flat;
    }
    const inner = `${indent}  `;
    return `{\n${entries.map(([k, v]) => `${inner}${keyOf(k)}: ${literal(v, inner)},`).join("\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}

const constants = (tables) => Object.entries(tables).map(([name, value]) => `export const ${name} = ${literal(value)};`).join("\n\n");

export function renderCatalogBlock(tables, commit) {
  return [BEGIN, `// Source: AgentCompass ${commit} ${ACCOUNTS_PATH}, ${PLAN_TEMPLATES_PATH}`, "", constants(tables), "", END].join("\n");
}

export function renderReferenceData(tables, commit) {
  return [
    "// GENERATED by scripts/sync-catalog.mjs: do not edit; run `npm run catalog:sync`.",
    `// Source: AgentCompass ${commit} ${FIVE_AXIS_PATH}, ${USER_SCORES_PATH}`,
    "// The category scores, panel targets, durations, plan capacities and maintainer manual scores the allocator reads.",
    "",
    constants(tables),
    "",
  ].join("\n");
}

export function expectedCatalogBlock() {
  return renderCatalogBlock(buildCatalogTables(agentCompassJson(ACCOUNTS_PATH), agentCompassJson(PLAN_TEMPLATES_PATH)), AGENTCOMPASS_COMMIT);
}

export function expectedReferenceData() {
  return renderReferenceData(buildReferenceTables(agentCompassJson(FIVE_AXIS_PATH), agentCompassJson(USER_SCORES_PATH)), AGENTCOMPASS_COMMIT);
}

/** A checkout may have CRLF line ends (`core.autocrlf`); the generated text is compared and written with LF. */
const withLf = (text) => text.replace(/\r\n/g, "\n");

export function currentBlock(rawSource = fs.readFileSync(CATALOG_PATH, "utf8")) {
  const source = withLf(rawSource);
  const from = source.indexOf(BEGIN);
  const to = source.indexOf(END);
  if (from < 0 || to < from) throw new Error(`${CATALOG_PATH}: no generated block`);
  return source.slice(from, to + END.length);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const expectedBlock = expectedCatalogBlock();
  const expectedData = expectedReferenceData();
  const source = withLf(fs.readFileSync(CATALOG_PATH, "utf8"));
  const current = currentBlock(source);
  const currentData = fs.existsSync(REFERENCE_DATA_PATH) ? withLf(fs.readFileSync(REFERENCE_DATA_PATH, "utf8")) : "";
  if (process.argv.includes("--check")) {
    const stale = [current !== expectedBlock && "src/catalog.js", currentData !== expectedData && "src/reference-data.js"].filter(Boolean);
    if (stale.length > 0) {
      console.error(`${stale.join(" and ")} differ from AgentCompass ${AGENTCOMPASS_COMMIT}; run npm run catalog:sync`);
      process.exit(1);
    }
    console.log(`src/catalog.js and src/reference-data.js match AgentCompass ${AGENTCOMPASS_COMMIT}`);
  } else {
    fs.writeFileSync(CATALOG_PATH, source.replace(current, () => expectedBlock));
    fs.writeFileSync(REFERENCE_DATA_PATH, expectedData);
    console.log(`src/catalog.js and src/reference-data.js generated from AgentCompass ${AGENTCOMPASS_COMMIT}`);
  }
}
