#!/usr/bin/env node
/**
 * Generate the data tables of `src/catalog.js` from AgentCompass's `references/accounts.json` at the pinned commit
 * (`scripts/agentcompass-pin.mjs`), plus `scripts/catalog-overlay.mjs` for what Magpie keeps of its own.
 *
 *   node scripts/sync-catalog.mjs          rewrite the generated block
 *   node scripts/sync-catalog.mjs --check  exit 1 if the block differs from what the pinned commit generates
 */
import fs from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { AGENTCOMPASS_COMMIT, agentCompassJson } from "./agentcompass-pin.mjs";
import {
  MAGPIE_MODELS,
  MODEL_OVERLAY,
  NEW_MODEL_DEFAULTS,
  POLICY_OVERLAY,
  ROUTE_TEXT,
} from "./catalog-overlay.mjs";

export const ACCOUNTS_PATH = "skills/agent-compass/references/accounts.json";
const CATALOG_PATH = fileURLToPath(new URL("../src/catalog.js", import.meta.url));
const BEGIN = "// BEGIN GENERATED by scripts/sync-catalog.mjs";
const END = "// END GENERATED by scripts/sync-catalog.mjs";

/** Provenance prose: long, and nothing routes on it. */
function dropProse(value) {
  if (Array.isArray(value)) return value.map(dropProse);
  if (!value || typeof value !== "object") return value;
  const out = {};
  for (const [key, val] of Object.entries(value)) {
    if (key === "basis" || key.endsWith("_basis") || key === "calibration_source") continue;
    out[key] = dropProse(val);
  }
  return out;
}

function rowsOf(table) {
  return Object.entries(table || {}).filter(([, row]) => row && typeof row === "object" && !Array.isArray(row));
}

function mergeDeep(base, extra) {
  const out = { ...base };
  for (const [key, val] of Object.entries(extra)) {
    out[key] = val && typeof val === "object" && !Array.isArray(val) ? mergeDeep(out[key] || {}, val) : val;
  }
  return out;
}

export function buildTables(accounts) {
  const models = {};
  for (const [name, row] of rowsOf(accounts.models)) {
    models[name] = { ...dropProse(row), ...(MODEL_OVERLAY[name] || NEW_MODEL_DEFAULTS) };
  }
  Object.assign(models, MAGPIE_MODELS);

  const routes = {};
  for (const [kind, route] of Object.entries(accounts.capability_policy.routes)) {
    const { effort: _prose, ...rest } = dropProse(route);
    routes[kind] = { ...rest, ...(ROUTE_TEXT[kind] || {}) };
  }

  const curves = {};
  for (const [name, row] of rowsOf(accounts.effort_curves)) curves[name] = dropProse(row);

  return {
    ROUTE_FIT_PEERS: dropProse(accounts.capability_policy.route_fit_peers),
    CANONICAL_ROUTES: routes,
    DEFAULT_MODELS: models,
    MODEL_ALIASES: accounts.aliases,
    UNMEASURED_MODELS: dropProse(accounts.unmeasured_models),
    SUPERSEDED_MODELS: Object.fromEntries(rowsOf(accounts.superseded).map(([name, row]) => [name, row.by])),
    EFFORT_CURVES: curves,
    DISPATCH_EFFORTS: accounts.dispatch_efforts,
    DEFAULT_SCORING_POLICY: mergeDeep(dropProse(accounts.scoring), POLICY_OVERLAY),
  };
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const keyOf = (key) => (IDENTIFIER.test(key) ? key : JSON.stringify(key));

function literal(value, indent = "") {
  if (Array.isArray(value)) {
    if (value.every((v) => v === null || typeof v !== "object")) {
      const flat = `[${value.map((v) => JSON.stringify(v)).join(", ")}]`;
      if (flat.length + indent.length <= 110) return flat;
    }
    const inner = `${indent}  `;
    return `[\n${value.map((v) => `${inner}${literal(v, inner)},`).join("\n")}\n${indent}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    if (entries.every(([, v]) => typeof v === "number")) {
      const flat = `{ ${entries.map(([k, v]) => `${keyOf(k)}: ${JSON.stringify(v)}`).join(", ")} }`;
      if (flat.length + indent.length <= 110) return flat;
    }
    const inner = `${indent}  `;
    return `{\n${entries.map(([k, v]) => `${inner}${keyOf(k)}: ${literal(v, inner)},`).join("\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}

export function renderBlock(tables, commit) {
  const consts = Object.entries(tables).map(([name, value]) => `export const ${name} = ${literal(value)};`);
  return [BEGIN, `// Source: AgentCompass ${commit} ${ACCOUNTS_PATH}`, "", consts.join("\n\n"), "", END].join("\n");
}

export function expectedBlock() {
  return renderBlock(buildTables(agentCompassJson(ACCOUNTS_PATH)), AGENTCOMPASS_COMMIT);
}

/** A checkout may have CRLF line ends (`core.autocrlf`); the block is compared and written with LF. */
const withLf = (text) => text.replace(/\r\n/g, "\n");

export function currentBlock(rawSource = fs.readFileSync(CATALOG_PATH, "utf8")) {
  const source = withLf(rawSource);
  const from = source.indexOf(BEGIN);
  const to = source.indexOf(END);
  if (from < 0 || to < from) throw new Error(`${CATALOG_PATH}: no generated block`);
  return source.slice(from, to + END.length);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const expected = expectedBlock();
  const source = withLf(fs.readFileSync(CATALOG_PATH, "utf8"));
  const current = currentBlock(source);
  if (process.argv.includes("--check")) {
    if (current !== expected) {
      console.error(`src/catalog.js differs from AgentCompass ${AGENTCOMPASS_COMMIT}; run node scripts/sync-catalog.mjs`);
      process.exit(1);
    }
    console.log(`src/catalog.js matches AgentCompass ${AGENTCOMPASS_COMMIT}`);
  } else {
    fs.writeFileSync(CATALOG_PATH, source.replace(current, () => expected));
    console.log(`src/catalog.js generated from AgentCompass ${AGENTCOMPASS_COMMIT}`);
  }
}
